"""Builds data/songs.js: looks up 30s iTunes previews for every song in songs.txt."""
import json, os, re, sys, time, unicodedata, urllib.parse, urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
ALIASES = {"(G)I-DLE": ["gidle", "idle"], "TOMORROW X TOGETHER": ["tomorrowxtogether", "txt"],
           "Agust D": ["agustd", "suga"], "Somi": ["somi", "jeonsomi"], "Jeon Somi": ["jeonsomi", "somi"],
           "Yena": ["yena", "choiyena"], "Jennie": ["jennie"], "ROSÉ": ["rose"], "LISA": ["lisa"],
           "Jung Kook": ["jungkook"], "Girls' Generation": ["girlsgeneration", "snsd"],
           "Zico": ["zico"], "Dean": ["dean"], "Crush": ["crush"], "Heize": ["heize"], "Hwasa": ["hwasa"],
           "Seulgi": ["seulgi"], "Wendy": ["wendy"], "KAI": ["kai"], "V": ["v"], "JIN": ["jin"], "RM": ["rm"],
           "BOL4": ["bol4", "bolbbalgan4"], "Kwon Eun Bi": ["kwoneunbi"], "IU": ["iu"]}
BAD = re.compile(r"\b(live|inst|instrumental|remix|acapella|a cappella|sped up|slowed|ver\.?|version|japanese|english|chinese|mix|edit|demo|karaoke|orchestra|acoustic|piano|mr|rock|ballad|band)\b", re.I)

def norm(s):
    s = unicodedata.normalize("NFKD", s).encode("ascii", "ignore").decode() or s
    return re.sub(r"[^a-z0-9]", "", s.lower())

CACHE_FILE = ROOT / "tools/.cache.json"
CACHE = json.loads(CACHE_FILE.read_text()) if CACHE_FILE.exists() else {}

def get(params):
    url = "https://itunes.apple.com/search?" + urllib.parse.urlencode(params)
    if url in CACHE:
        return CACHE[url]
    for attempt in range(8):
        try:
            with urllib.request.urlopen(url, timeout=30) as r:
                res = json.load(r)["results"]
            CACHE[url] = res
            CACHE_FILE.write_text(json.dumps(CACHE))
            time.sleep(3)
            return res
        except Exception as e:
            print("  retry", attempt, e, file=sys.stderr, flush=True); time.sleep(6 * (attempt + 1))
    return []

def artist_ok(artist, name):
    n = norm(name)
    keys = ALIASES.get(artist, [norm(artist)])
    if len(keys[0]) <= 3:  # short names: require exact primary artist
        return any(re.split(r"[^a-z0-9]", name.lower().replace(" ", ""))[0] == k for k in keys) or any(n == k for k in keys)
    return any(n.startswith(k) or k in n for k in keys)

def best(title, artist, tracks, kind="song"):
    t = norm(title)
    cands = []
    for tr in tracks:
        if tr.get("kind") != kind or not tr.get("previewUrl"): continue
        if not artist_ok(artist, tr["artistName"]): continue
        name = tr["trackName"]
        base = re.sub(r"\s*[\(\[].*?[\)\]]", "", name)
        nb, nn = norm(base), norm(name)
        if not t or not (nb == t or nn == t or nn.startswith(t) or (len(t) > 4 and t in nn)): continue
        extra = name[len(base):] if nb == t else name
        penalty = (0 if nb == t or nn == t else 2) + (3 if BAD.search(extra) else 0) + (1 if "feat" in name.lower() and nb != t else 0)
        cands.append((penalty, len(name), tr))
    cands.sort(key=lambda c: (c[0], c[1]))
    return cands[0][2] if cands and cands[0][0] < 3 else None

def main():
    by_artist = {}
    for line in (ROOT / "tools/songs.txt").read_text().splitlines():
        if "|" not in line: continue
        a, titles = line.split("|", 1)
        lst = by_artist.setdefault(a.strip(), [])
        for t in titles.split(";"):
            t = t.strip()
            if t and norm(t) not in {norm(x) for x in lst}: lst.append(t)
    out, seen, missing = [], set(), []
    for artist, titles in by_artist.items():
        tracks = get({"term": artist, "entity": "song", "attribute": "artistTerm", "limit": 200, "country": "US"})
        mvs = get({"term": artist, "entity": "musicVideo", "attribute": "artistTerm", "limit": 200, "country": "US"})
        for title in titles:
            tr = best(title, artist, tracks)
            if not tr and os.environ.get("FALLBACK", "1") == "1":
                tr = best(title, artist, get({"term": f"{artist} {title}", "entity": "song", "limit": 25, "country": "US"}))
            if not tr:
                missing.append(f"{artist} - {title}"); continue
            if tr["trackId"] in seen: continue
            seen.add(tr["trackId"])
            mv = best(title, artist, mvs, kind="music-video")
            out.append({"t": title, "a": artist, "p": tr["previewUrl"], **({"v": mv["previewUrl"]} if mv else {}),
                        "c": tr.get("artworkUrl100", "").replace("100x100bb", "300x300bb"),
                        "y": (tr.get("releaseDate") or "")[:4]})
        print(f"{artist}: total {len(out)}", file=sys.stderr, flush=True)
    (ROOT / "data").mkdir(exist_ok=True)
    (ROOT / "data/songs.js").write_text("// Generated by tools/fetch_previews.py\nwindow.SONGS = " + json.dumps(out, ensure_ascii=False, indent=0) + ";\n")
    (ROOT / "tools/missing.txt").write_text("\n".join(missing) + "\n")
    print(f"DONE {len(out)} songs ({sum(1 for o in out if 'v' in o)} with MV), {len(missing)} missing", file=sys.stderr)

if __name__ == "__main__":
    main()
